package app.jpcard.reader.data

import android.content.Context

/** A rail station with its Japanese and English name. */
data class Station(val name: String, val nameEn: String, val company: String, val line: String) {
    fun displayName(english: Boolean): String = if (english && nameEn.isNotEmpty()) nameEn else name
}

/** A bus operator with its Japanese and English name. */
data class BusOperator(val name: String, val nameEn: String) {
    fun displayName(english: Boolean): String = if (english && nameEn.isNotEmpty()) nameEn else name
}

/**
 * Station and bus stop tables (in assets, generated by tools/gen_stations.py).
 * - stations.tsv: rail, key = area (2 bits) << 16 | line << 8 | station
 * - bus.tsv: bus, key = operator << 16 | stop (stop 0 means only the operator is known)
 *
 * Bus stop names are Japanese only: the available English stop names are unreliable.
 */
object Stations {
    @Volatile
    private var rail: Map<Int, Station> = emptyMap()

    @Volatile
    private var busStops: Map<Long, String> = emptyMap()

    @Volatile
    private var busOperators: Map<Int, BusOperator> = emptyMap()

    val loaded: Boolean get() = rail.isNotEmpty()

    /** Call off the main thread; takes a few tens of milliseconds. */
    fun load(context: Context) {
        if (loaded) return
        val r = HashMap<Int, Station>(8192)
        context.assets.open("stations.tsv").bufferedReader(Charsets.UTF_8).useLines { lines ->
            lines.forEach { line ->
                val p = line.split('\t')
                if (p.size >= 5) p[0].toIntOrNull(16)?.let { r[it] = Station(p[1], p[4], p[2], p[3]) }
            }
        }
        val stops = HashMap<Long, String>(8192)
        val operators = HashMap<Int, BusOperator>(256)
        context.assets.open("bus.tsv").bufferedReader(Charsets.UTF_8).useLines { lines ->
            lines.forEach { line ->
                val p = line.split('\t')
                val key = p.getOrNull(0)?.toLongOrNull(16) ?: return@forEach
                if (p.size < 4) return@forEach
                val op = (key shr 16).toInt()
                // Operator names are only on each operator's first row.
                if (p[2].isNotEmpty()) operators.putIfAbsent(op, BusOperator(p[2], p[3]))
                if (p[1].isNotEmpty()) stops[key] = p[1]
            }
        }
        busStops = stops
        busOperators = operators
        rail = r
    }

    fun find(area: Int, line: Int, station: Int): Station? =
        rail[((area and 0x03) shl 16) or ((line and 0xFF) shl 8) or (station and 0xFF)]

    fun busOperator(operator: Int): BusOperator? = busOperators[operator and 0xFFFF]

    fun busStop(operator: Int, stop: Int): String? =
        if (stop == 0) null else busStops[((operator.toLong() and 0xFFFF) shl 16) or (stop.toLong() and 0xFFFF)]
}
